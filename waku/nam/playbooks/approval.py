"""approval (FRS F37, F38, F45): the approval file for the submitted PR, and
who approves it (S8).

  1. The procurement file. There is no Aarohan connector, so the case goes
     through Procurix.ai's own e-office approval (F45) under its own file
     number (FILE-<case>). An Aarohan file made by hand is linked with
     answer {question_id: "aarohan_file", value: "NRL/MAT/2026/123"}.
  2. The approving authority, by the delegation of authority
     (policy/doa.json): the first level whose limit covers the estimated
     value. NRL's DoA is not given yet, so with no levels the approver names
     the authority: answer {question_id: "authority", value: "GM (Materials)"}.
     The estimated value is provisional (R4), and so is the level it picks.
  3. The Administrative Approval Note (ANN, F38), generated by Procurix.ai
     from the case and stored as a .docx in the case's documents.

The file is complete once the authority is known; the stage machine then
puts the approval itself (approve, an irreversible action) to an approver.
A rejection is given with a reason on that confirmation.
"""

from __future__ import annotations

import json
import re
from functools import cache
from pathlib import Path

from waku.nam import need as need_store
from waku.nam import orchestrator, store
from waku.nam.errors import NamError
from waku.nam.playbooks import Outcome, documents, need_classify

POLICY = Path(__file__).resolve().parents[1] / "policy" / "doa.json"
ANSWERS = ("authority", "aarohan_file")
_FILE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/._-]{2,59}$")


@cache
def policy() -> dict:
    return json.loads(POLICY.read_text(encoding="utf-8"))


def doa_level(total) -> dict | None:
    """The DoA level for an estimated value, or None without levels."""
    for level in policy().get("levels") or []:
        if total is not None and (level["up_to"] is None or total <= level["up_to"]):
            return level
    return None


def _ann_blocks(need, wf, file_number: str, authority: str, basis: str) -> list[tuple]:
    est = orchestrator._artifact(wf, "estimate") or {}
    pr = (wf["actions"].get("submit_pr") or {}).get("result") or {}
    ref = orchestrator._artifact(wf, "pr_reference") or {}
    form = (orchestrator._artifact(wf, "guided_form") or {}).get("answers") or {}
    compliance = orchestrator._artifact(wf, "compliance") or {}
    package = orchestrator._artifact(wf, "package") or {}
    route = need_classify.route(need)
    total = est.get("total")
    rows = [["Case", need.need_id], ["File", file_number],
            ["Subject", need.raw_text.split(";")[0][:300]],
            ["Category", route["category"] or ""],
            ["Procurement type", (need.procurement_type or {}).get("value") or ""],
            ["Tender type", (need.tender_type or {}).get("value") or ""],
            ["Estimated value", f"Rs {total:,.2f} (provisional)" if total is not None
             else "not estimated"],
            ["PR", f"{pr.get('pr_number') or ''}" + (f" (SAP {ref['sap_pr']})"
                                                       if ref.get("sap_pr") else "")],
            ["Precedents", ", ".join(need.selected_cases) or "none (guided form)"],
            ["Justification", str(form.get("justification") or "")[:500]],
            ["Approving authority", f"{authority} ({basis})"]]
    blocks = [("p", "Administrative Approval Note, generated by Procurix.ai (FRS F38)."),
              ("table", [["", ""], *rows])]
    applied = [r["text"] for r in compliance.get("requirements") or [] if r.get("apply")]
    if applied:
        blocks += [("h", "Compliance requirements"), *[("p", t) for t in applied[:30]]]
    if package.get("documents"):
        blocks += [("h", "Package"), ("table", [["document", "version"],
                                                *[[d["kind"], d.get("version") or ""]
                                                  for d in package["documents"]]])]
    return blocks


def handle(request: dict, ctx) -> Outcome:
    case_id = request["case_id"]
    need = need_store.load(ctx.conn, case_id)
    if need is None:
        raise NamError("not_found", f"no case {case_id}")
    wf = orchestrator.workflow(need)
    if "submit_pr" not in wf["actions"]:
        raise NamError("stage_gate", "the PR is not submitted (pr.submit)", case_id=case_id)
    answer = request.get("answer") or {}
    asked = answer.get("question_id") or ""
    if asked and asked not in ANSWERS:
        raise NamError("bad_request", f"approval asks only {', '.join(ANSWERS)}")
    stored = orchestrator._artifact(wf, "approval_file") or {}
    warnings: list[str] = []
    total = (orchestrator._artifact(wf, "estimate") or {}).get("total")
    level = doa_level(total)
    authority, basis = stored.get("authority"), stored.get("authority_basis") or ""
    if level:
        authority, basis = level["authority"], f"DoA level up to {level['up_to'] or 'any value'}"
    elif not policy().get("levels"):
        warnings.append("NRL's delegation of authority is not configured (policy/doa.json): "
                        "the approver names the approving authority.")
    aarohan = stored.get("aarohan_file")
    given = str(answer.get("value") or "").strip()
    if asked == "authority" and given:
        if level:
            warnings.append(f"The DoA gives {level['authority']} for this value: the authority "
                            "is not chosen by hand.")
        elif not 3 <= len(given) <= 120 or not re.match(r"^[\w ().,/&-]+$", given):
            warnings.append("The authority is a name or designation, 3 to 120 characters.")
        else:
            authority, basis = given, f"named by {store.current().user}"
    if asked == "aarohan_file" and given:
        if _FILE.match(given):
            aarohan = given
        else:
            warnings.append(f"'{given[:40]}' is not an Aarohan file number.")

    file_number = f"FILE-{case_id}"
    complete = bool(authority)
    value = {"summary": (f"file {aarohan or file_number}"
                         + (f", for approval by {authority}" if authority else
                            ", approving authority not named"))[:300],
             "complete": complete, "file_number": file_number, "aarohan_file": aarohan,
             "route": "aarohan" if aarohan else "procurix",
             "authority": authority, "authority_basis": basis,
             "estimated_value": total, "ann": stored.get("ann")}
    core = {k: v for k, v in value.items() if k != "ann"}
    changed = core != {k: v for k, v in stored.items() if k != "ann"}
    if changed and complete:
        doc_id, version = documents.store_docx(
            ctx, case_id, "ann", "Administrative Approval Note",
            _ann_blocks(need, wf, aarohan or file_number, authority, basis),
            stored.get("ann") or {}, warnings, flow="approval")
        value["ann"] = {"doc_id": doc_id, "version": version} if doc_id else None
    done = wf["actions"].get("approve")
    questions = ()
    if not authority:
        questions = ({"id": "authority", "source": "harness", "options": [],
                      "text": "Who approves this case? Give the approving authority.",
                      "why": "The DoA decides who approves; NRL's is not configured yet."},)
    return Outcome(
        case_id=case_id, status="ok" if complete else "needs_input",
        result={"file_number": file_number, "aarohan_file": aarohan,
                "authority": authority, "authority_basis": basis, "complete": complete,
                "ann": value["ann"], "approved": bool(done),
                "aarohan": "not sent: no Aarohan connector, approval in Procurix.ai (F45)"},
        questions=questions, warnings=tuple(warnings),
        next=("package.publish", "handoff.nit") if done else (),
        artifacts={"approval_file": value} if changed else {})
